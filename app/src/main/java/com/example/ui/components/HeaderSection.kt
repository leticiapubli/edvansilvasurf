                modifier = Modifier
                    .fillMaxWidth()
                    .height(148.dp)
            ) {
                Image(
                    painter = painterResource(id = R.drawable.surf_hero_banner_1793560083672),
                    contentDescription = "Praia e ondas do dia",
                    contentScale = ContentScale.Crop,
                    modifier = Modifier.fillMaxWidth()
                )

                // Subtle gradient overlay for readability
                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(148.dp)
