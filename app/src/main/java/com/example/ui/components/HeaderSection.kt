                                    fontWeight = FontWeight.Medium
                                )
                            }
                        }

                        // Discreet Admin button
                        Surface(
                            shape = RoundedCornerShape(12.dp),
                            color = if (isAdminMode) MaterialTheme.colorScheme.secondary else Color.White.copy(alpha = 0.15f),
