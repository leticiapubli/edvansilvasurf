                            text = "Modo Instrutor ativo: Edite horários, cancele por tempo ruim ou gerencie vagas.",
                            fontSize = 12.sp,
                            fontWeight = FontWeight.SemiBold,
                            color = MaterialTheme.colorScheme.onSecondaryContainer
                        )
                    }
                }
            }
        }
    }
}
